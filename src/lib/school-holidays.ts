/** Schulferien-Bezeichnung an einem Tag (null = keine Ferien oder außerhalb der Datenabdeckung). */
export function schoolHolidayOn(dateIso: string, state: StateCode): SchoolHolidayName | null {
  const list = SCHOOL_HOLIDAYS[state];
  if (!list) return null;
  for (const [name, from, to] of list) if (from <= dateIso && dateIso <= (to ?? from)) return name;
  return null;
}

/** Liegen für diesen Tag Schulferien-Daten vor? */
export const schoolHolidaysCovered = (dateIso: string) => SCHOOL_HOLIDAYS_META.coverage.from <= dateIso && dateIso <= SCHOOL_HOLIDAYS_META.coverage.to;
